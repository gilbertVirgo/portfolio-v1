// Compiles design/email/confirmation.mjml into a string module the contact function imports.
// Run with `npm run email` after editing the template; the output is committed.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const html = execFileSync('npx', ['-y', 'mjml@4', 'design/email/confirmation.mjml', '--config.validationLevel=strict', '--config.minify=true', '-s'], { encoding: 'utf8' })
if (!html.includes('{{name}}')) throw new Error('compiled email lost its {{name}} placeholder')
writeFileSync('netlify/lib/confirmation-email.ts', `// Generated by scripts/build-email.mjs from design/email/confirmation.mjml. Do not edit.\nexport const confirmationHtml = ${JSON.stringify(html.trim())}\n`)
console.log(`confirmation-email.ts written (${html.length} bytes)`)
